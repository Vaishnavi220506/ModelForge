"""Generate the LaTeX tables and numbers of the ForgeCert paper from the result files.

Author: Vaishnavi
Usage: python make_tables.py <certbench json>... --mcu mcu_results.json --out ../paper/forgecert_tables.tex
(standard library only)

Writes \\newcommand macros (\\FC...) with headline numbers and the tables
\\FCTableMain, \\FCTableAblation, \\FCTableZoo and \\FCTableMCU.
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ZOO = ("lenet", "dscnn", "resnet")
MAIN = [("uniform_int8", "Uniform int8"), ("uniform_int8_calibrated", "Uniform int8, calibrated"),
        ("uniform_int4", "Uniform int4/int8"), ("uniform_int16", "Uniform int16"),
        ("accuracy_guided", "Accuracy-guided"), ("forgecert", "\\textbf{ForgeCert} (bytes)"),
        ("forgecert_calibrated", "\\textbf{ForgeCert}, calibrated"), ("forgecert_latency", "\\textbf{ForgeCert} (latency)")]
ABLATIONS = [("forgecert", "ForgeCert (bytes)"), ("ablation_interval_domain", "interval domain"),
             ("ablation_per_tensor_scales", "per-tensor scales"),
             ("ablation_no_modular_accumulation", "no modular accumulators"),
             ("ablation_no_splitting", "no input splitting"), ("ablation_no_falsifier", "no falsifier"),
             ("ablation_no_minimise", "no local search"), ("ablation_uniform_refine", "raise all sources"),
             ("ablation_random_refine_s1", "raise a random source"),
             ("ablation_latency_greedy_search", "latency: greedy only")]
OPERATORS = {"lenet": "conv, max-pool, dense", "lenet_avg": "conv, avg-pool, dense",
             "dscnn": "conv, depthwise, BN, GAP", "resnet": "conv, BN, residual add, GAP"}


def suite_of(case):
    if any(a in case["model"] for a in ZOO):
        return "zoo"
    return "image" if case["model"].startswith(("mnist", "fashion", "cifar")) else "tabular"


def tex(text):
    return str(text).replace("_", "\\_")


def aggregate(cases, name):
    a = defaultdict(float)
    for case in cases:
        outcomes = {o["name"]: o for o in case["outcomes"]}
        if name not in outcomes:
            continue
        o, int8 = outcomes[name], outcomes["uniform_int8"]
        a["n"] += 1
        a["robust"] += case["robust"]
        a["proved"] += o["proved"]
        a["certified"] += o["unproved"] == 0
        a["cex"] += o["counterexamples"]
        a["flash_fp32"] += o["flash"] / case["float32_bytes"]
        a["cycles_int8"] += o["cycles"] / max(1.0, int8["cycles"])
        a["seconds"] += o["seconds"]
    return a


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("certbench", nargs="+")
    parser.add_argument("--mcu", default=str(ROOT / "results" / "mcu_results.json"))
    parser.add_argument("--out", default=str(ROOT.parent / "paper" / "forgecert_tables.tex"))
    args = parser.parse_args()
    cases = []
    for path in args.certbench:
        cases += json.load(open(path))["cases"]
    suites = {s: [c for c in cases if suite_of(c) == s] for s in ("tabular", "image", "zoo")}
    accuracy = {}
    for f in ("image_models.json", "cnn_zoo.json"):
        p = ROOT / "results" / f
        if p.exists():
            accuracy.update(json.load(open(p))["models"])
    out = ["% Generated by research/make_tables.py from the benchmark results; do not edit by hand."]
    words = {"16": "Sixteen", "8": "Eight", "4": "Four"}

    def macro(name, value):
        for digits, word in words.items():
            name = name.replace(digits, word)
        out.append(f"\\newcommand{{\\FC{name}}}{{{value}}}")

    # Headline numbers.
    audits = [c["audit"] for c in cases]
    checks = [c["checker"] for c in cases if c["checker"]["seconds"] >= 0]
    macro("Cases", len(cases))
    macro("Models", len({c["model"] for c in cases}))
    macro("Regions", sum(c["robust"] for c in cases))
    macro("AuditSamples", f"{sum(a['samples'] for a in audits):,}".replace(",", "{,}"))
    macro("AuditViolations", sum(a["violations"] for a in audits))
    macro("CheckerValid", sum(c["valid"] for c in checks))
    macro("CheckerTotal", len(checks))
    macro("CheckerMaxSeconds", f"{max(c['seconds'] for c in checks):.1f}")
    for suite, group in suites.items():
        if not group:
            continue
        key = suite.capitalize()
        macro(f"{key}Cases", len(group))
        macro(f"{key}Robust", sum(c["robust"] for c in group))
        for name, _ in MAIN:
            a = aggregate(group, name)
            if a["n"]:
                tag = "".join(w.capitalize() for w in name.split("_"))
                macro(f"{key}{tag}Proved", int(a["proved"]))
                macro(f"{key}{tag}Certified", int(a["certified"]))
                macro(f"{key}{tag}Cex", int(a["cex"]))
                macro(f"{key}{tag}Flash", f"{100 * a['flash_fp32'] / a['n']:.1f}")
    exact = gap = n = 0
    for case in cases:
        e = case["exhaustive"]
        if e["optimum_cost"] is None or e["optimum_cost"] < 0:
            continue
        ours = next(o for o in case["outcomes"] if o["name"] == "forgecert")
        if ours["unproved"]:
            continue
        n += 1
        exact += abs(ours["cost"] - e["optimum_cost"]) < 0.5
        gap += ours["cost"] / e["optimum_cost"] - 1
    macro("OptimumExact", exact)
    macro("OptimumCases", n)
    macro("OptimumGap", f"{100 * gap / max(1, n):.1f}")

    # Main table: one block per suite.
    rows = ["\\setlength{\\tabcolsep}{3.5pt}\\begin{tabular}{@{}lrrrrr@{}}", "\\toprule",
            "Method & Certified & Proved & Cex & Flash & Cycles \\\\",
            " & cases & regions & regions & /fp32 & /int8 \\\\", "\\midrule"]
    for suite, group in suites.items():
        if not group:
            continue
        rows.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{suite}: {len(group)} cases, "
                    f"{sum(c['robust'] for c in group)} robust regions}}}} \\\\")
        for name, label in MAIN:
            a = aggregate(group, name)
            if not a["n"]:
                continue
            rows.append(f"{label} & {int(a['certified'])}/{int(a['n'])} & {int(a['proved'])} & {int(a['cex'])} & "
                        f"{100 * a['flash_fp32'] / a['n']:.0f}\\% & {a['cycles_int8'] / a['n']:.2f} \\\\")
        rows.append("\\midrule")
    rows[-1] = "\\bottomrule"
    rows.append("\\end{tabular}")
    out.append("\\newcommand{\\FCTableMain}{%\n" + "\n".join(rows) + "}")

    # Ablations (suites that ran them).
    rows = ["\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
            "Variant & Certified & Proved & Flash/fp32 & Time (s) \\\\", "\\midrule"]
    group = [c for c in cases if suite_of(c) in ("tabular", "image")]
    for name, label in ABLATIONS:
        a = aggregate(group, name)
        if not a["n"]:
            continue
        rows.append(f"{label} & {int(a['certified'])}/{int(a['n'])} & {int(a['proved'])}/{int(a['robust'])} & "
                    f"{100 * a['flash_fp32'] / a['n']:.1f}\\% & {a['seconds']:.0f} \\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    out.append("\\newcommand{\\FCTableAblation}{%\n" + "\n".join(rows) + "}")

    # Architecture zoo.
    rows = ["\\begin{tabular}{@{}llrrrrrr@{}}", "\\toprule",
            "Model & Operators & Acc. & Robust & \\multicolumn{2}{c}{Proved} & Cex & Flash \\\\",
            "\\cmidrule(lr){5-6}", " & & & & int8 & ForgeCert & int8 & /fp32 \\\\", "\\midrule"]
    for case in suites["zoo"]:
        o = {x["name"]: x for x in case["outcomes"]}
        arch = case["model"].split("_", 1)[1]
        acc = accuracy.get(case["model"], {}).get("test_accuracy")
        rows.append(f"{tex(case['model'])} & {OPERATORS.get(arch, '')} & {100 * acc:.1f} & {case['robust']} & "
                    f"{o['uniform_int8']['proved']} & {o['forgecert']['proved']} & {o['uniform_int8']['counterexamples']} & "
                    f"{100 * o['forgecert']['flash'] / case['float32_bytes']:.0f}\\% \\\\")
    rows += ["\\bottomrule", "\\end{tabular}"]
    out.append("\\newcommand{\\FCTableZoo}{%\n" + "\n".join(rows) + "}")

    # Microcontroller.
    if Path(args.mcu).exists():
        mcu = json.load(open(args.mcu))["results"]
        rows = ["\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule",
                "Model & Code & Proved & Flash & RAM & kcycles & Bit-exact \\\\", "\\midrule"]
        names = {"forgecert": "ForgeCert", "forgecert_latency": "ForgeCert (lat.)", "uniform_int8": "int8"}
        last = None
        exact_all = all(r["avr_matches_host"] for r in mcu)
        for r in mcu:
            if r["model"] != last and last is not None:
                rows.append("\\midrule")
            first = r["model"] != last
            last = r["model"]
            model = f"{tex(r['model'])}" + ("$^\\dagger$" if r.get("mcu") == "atmega1284p" else "") if first else ""
            rows.append(f"{model} & {names[r['variant']]} & {r['proved']}/{r['proved'] + r['unproved']} & "
                        f"{r['avr_int']['flash']:,} & {r['avr_int']['ram']:,} & {r['avr_int_cycles_mean'] / 1000:,.0f} & "
                        f"{'yes' if r['avr_matches_host'] else 'no'} \\\\".replace(",", "{,}"))
            if r["variant"] == "forgecert":
                f = r.get("avr_float", {})
                if f.get("fits"):
                    rows.append(f" & float32 & -- & {f['flash']:,} & {f['ram']:,} & "
                                f"{r['avr_float_cycles_mean'] / 1000:,.0f} & "
                                f"{'yes' if r.get('avr_float_matches_host') else 'no'} \\\\".replace(",", "{,}"))
                else:
                    rows.append(" & float32 & \\multicolumn{5}{c}{does not fit} \\\\")
        rows += ["\\bottomrule", "\\end{tabular}"]
        out.append("\\newcommand{\\FCTableMCU}{%\n" + "\n".join(rows) + "}")
        macro("MCUConfigs", len(mcu))
        macro("MCUExact", "all" if exact_all else "not all")
    Path(args.out).write_text("\n".join(out) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
